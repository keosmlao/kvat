/**
 * Translate a dot-path message key. Falls back to Lao, then to the raw key
 * so a typo is visible in the UI rather than crashing.
 *
 * Usage: t("lo", "nav", "dashboard") → "ໜ້າຫຼັກ"
 */
export function t(locale: Locale, ...path: string[]): string {
  const cur = walk(dict[locale], path);
  if (cur !== undefined) return cur;
  // Fallback to source locale
  const fallback = walk(dict.lo, path);
  if (fallback !== undefined) return fallback;
  return path.join(".");
}

function walk(d: unknown, path: string[]): string | undefined {
  let cur: unknown = d;
  for (const k of path) {
    if (cur && typeof cur === "object" && k in (cur as Record<string, unknown>)) {
      cur = (cur as Record<string, unknown>)[k];
    } else {
      return undefined;
    }
  }
  return typeof cur === "string" ? cur : undefined;
}

export function isLocale(value: unknown): value is Locale {
  return value === "lo" || value === "th" || value === "en";
}
